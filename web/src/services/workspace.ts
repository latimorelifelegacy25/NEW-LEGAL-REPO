/**
 * Upload a text or markdown legal file to Google Drive
 */
export async function uploadToGoogleDrive(
  accessToken: string,
  filename: string,
  content: string,
  mimeType = 'text/plain'
): Promise<GoogleDriveFile> {
  const metadata = {
    name: filename,
    mimeType: mimeType,
    description: 'Generated by PA Legal Reference & Practice Portal'
  };

  const boundary = '-------314159265358979323846';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    `Content-Type: ${mimeType}\r\n\r\n` +
    content +
    closeDelimiter;

  const response = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,mimeType,webViewLink,createdTime',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': `multipart/related; boundary=${boundary}`
      },
      body: multipartRequestBody
    }
  );

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Google Drive API error (${response.status}): ${errorText}`);
  }

  return response.json();
}

/**
 * List files created in Google Drive by the user
 */
export async function listGoogleDriveFiles(accessToken: string): Promise<GoogleDriveFile[]> {
  const query = encodeURIComponent("trashed = false");
  const response = await fetch(
    `https://www.googleapis.com/drive/v3/files?q=${query}&fields=files(id,name,mimeType,webViewLink,createdTime)&orderBy=createdTime desc&pageSize=20`,
    {
      headers: {
        Authorization: `Bearer ${accessToken}`
      }
    }
  );

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Google Drive list files error (${response.status}): ${errorText}`);
  }

  const data = await response.json();
  return data.files || [];
}

/**
 * Create a formatted Google Document with legal pleading or analysis content
 */
export async function createGoogleDoc(
  accessToken: string,
  title: string,
  bodyText: string
): Promise<GoogleDocResult> {
  // 1. Create blank doc
  const createRes = await fetch('https://docs.googleapis.com/v1/documents', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({ title })
  });

  if (!createRes.ok) {
    const errText = await createRes.text();
    throw new Error(`Google Docs creation error (${createRes.status}): ${errText}`);
  }

  const docData = await createRes.json();
  const documentId = docData.documentId;

  // 2. Insert formatted text content
  if (bodyText.trim()) {
    const updateRes = await fetch(
      `https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`,
      {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${accessToken}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify({
          requests: [
            {
              insertText: {
                location: { index: 1 },
                text: `${bodyText}\n\n[Prepared via Pennsylvania Legal Practice Portal - Unified Judicial System]`
              }
            }
          ]
        })
      }
    );

    if (!updateRes.ok) {
      console.warn('Doc created, but failed to insert text content:', await updateRes.text());
    }
  }

  return {
    documentId,
    title,
    url: `https://docs.google.com/document/d/${documentId}/edit`
  };
}

/**
 * Create a statutory legal task in Google Tasks
 */
export async function createGoogleTask(
  accessToken: string,
  title: string,
  notes: string,
  dueDate?: string // YYYY-MM-DD
): Promise<GoogleTaskResult> {
  const taskPayload: any = {
    title,
    notes
  };

  if (dueDate) {
    // RFC 3339 format for Google Tasks
    taskPayload.due = new Date(dueDate).toISOString();
  }

  const response = await fetch('https://tasks.googleapis.com/tasks/v1/lists/@default/tasks', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify(taskPayload)
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Google Tasks error (${response.status}): ${errorText}`);
  }

  return response.json();
}

