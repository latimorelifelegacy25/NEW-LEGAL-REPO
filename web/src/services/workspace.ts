/**
 * Send a message or update to a Google Chat space
 */
export async function sendGoogleChatMessage(
  accessToken: string,
  spaceName: string,
  text: string
): Promise<{ name: string; text: string }> {
  // If no spaceName is provided, list user spaces
  let targetSpace = spaceName;
  if (!targetSpace) {
    const spacesRes = await fetch('https://chat.googleapis.com/v1/spaces?pageSize=5', {
      headers: { Authorization: `Bearer ${accessToken}` }
    });
    if (spacesRes.ok) {
      const spacesData = await spacesRes.json();
      if (spacesData.spaces && spacesData.spaces.length > 0) {
        targetSpace = spacesData.spaces[0].name;
      }
    }
  }

  if (!targetSpace) {
    throw new Error('No Google Chat space found. Please create or specify a Chat Space name.');
  }

  const response = await fetch(`https://chat.googleapis.com/v1/${targetSpace}/messages`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({ text })
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Google Chat API error (${response.status}): ${errText}`);
  }

  return response.json();
}

/**
 * Create a new Client Intake Questionnaire in Google Forms
 */
export async function createGoogleForm(
  accessToken: string,
  title: string,
  description: string,
  questions: { title: string; required?: boolean }[]
): Promise<GoogleFormResult> {
  // 1. Create Form
  const createRes = await fetch('https://forms.googleapis.com/v1/forms', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      info: {
        title,
        documentTitle: title
      }
    })
  });

  if (!createRes.ok) {
    const errorText = await createRes.text();
    throw new Error(`Google Forms error (${createRes.status}): ${errorText}`);
  }

  const formData = await createRes.json();
  const formId = formData.formId;

  // 2. Add question items via batchUpdate
  if (questions.length > 0) {
    const requests = questions.map((q, idx) => ({
      createItem: {
        item: {
          title: q.title,
          questionItem: {
            question: {
              required: q.required ?? true,
              textQuestion: {
                paragraph: true
              }
            }
          }
        },
        location: { index: idx }
      }
    }));

    await fetch(`https://forms.googleapis.com/v1/forms/${formId}:batchUpdate`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({ requests })
    });
  }

  return {
    formId,
    responderUri: formData.responderUri || `https://docs.google.com/forms/d/${formId}/viewform`,
    editUrl: `https://docs.google.com/forms/d/${formId}/edit`,
    title
  };
}

/**
 * Schedule a client consultation or conciliation preparation space in Google Meet
 */
export async function createGoogleMeetSpace(
  accessToken: string
): Promise<GoogleMeetResult> {
  const response = await fetch('https://meet.googleapis.com/v1/spaces', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      config: {
        accessType: 'OPEN'
      }
    })
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Google Meet API error (${response.status}): ${errorText}`);
  }

  const data = await response.json();
  return {
    meetingUri: data.meetingUri,
    meetingCode: data.meetingCode || data.meetingUri?.split('/').pop() || 'meet-call'
  };
}
